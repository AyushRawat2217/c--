/*APPROACH

The recursion answers the question:

```
"How many valid good-number strings can be formed
 starting from the current index?"
```

Rules:

* Even indices (0, 2, 4, ...) can contain:
  {0, 2, 4, 6, 8}
  => 5 choices

* Odd indices (1, 3, 5, ...) can contain:
  {2, 3, 5, 7}
  => 4 choices

Recursive Logic:

1. Base Case:
   If index == n, it means we have successfully
   formed one complete valid string.

   Return 1.

   Think of this as:
   "One valid combination found."

2. Recursive Case:

   If current index is even:
   Try all 5 valid even digits.
   Add the number of valid strings obtained
   from each choice.

   If current index is odd:
   Try all 4 valid prime digits.
   Add the number of valid strings obtained
   from each choice.

3. The final answer is the sum of all valid
   combinations generated by the recursion.

---

DRY RUN (n = 2)

Indices:
0 1

Index 0:
5 choices
{0, 2, 4, 6, 8}

Index 1:
4 choices
{2, 3, 5, 7}

---

Initial Call:

```
countGoodNumbers(0, 2)
```

---

STEP 1

countGoodNumbers(0, 2)

index = 0 (even)

Loop runs 5 times:

```
result =
    count(1,2)
  + count(1,2)
  + count(1,2)
  + count(1,2)
  + count(1,2)
```

Need to find count(1,2).

---

STEP 2

countGoodNumbers(1, 2)

index = 1 (odd)

Loop runs 4 times:

```
result =
    count(2,2)
  + count(2,2)
  + count(2,2)
  + count(2,2)
```

Need to find count(2,2).

---

STEP 3

countGoodNumbers(2, 2)

index == n

Base Case reached.

This means:

```
One complete valid string has been formed.
```

Return:

```
1
```

---

STEP 4

Back to countGoodNumbers(1,2)

Each count(2,2) returns 1.

Therefore:

```
count(1,2)
= 1 + 1 + 1 + 1
= 4
```

Meaning:

```
From index 1 onward,
there are 4 valid possibilities.
```

Return 4.

---

STEP 5

Back to countGoodNumbers(0,2)

Each count(1,2) returns 4.

Therefore:

```
count(0,2)
= 4 + 4 + 4 + 4 + 4
= 20
```

Meaning:

```
From index 0 onward,
there are 20 valid good-number strings.
```

Return 20.

---

TREE VISUALIZATION

count(0,2)
|
|---- count(1,2) = 4
|---- count(1,2) = 4
|---- count(1,2) = 4
|---- count(1,2) = 4
|---- count(1,2) = 4

Total:

```
4 + 4 + 4 + 4 + 4
= 20
```

---

KEY INSIGHT

The recursion conceptually generates every valid
combination.

Whenever a complete valid string is formed:

```
index == n
```

it contributes:

```
1
```

All these 1's are added together to obtain the
total number of valid good-number strings.
*/

